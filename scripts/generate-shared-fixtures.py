def build_circular_aggregate(profile: dict) -> dict:
    minimum_resultant = float(profile["minCircularResultantLength"])
    windows = [
        {"id": "tight-cluster", "samples": [84.7, 85.3, 84.9, 85.4, 85.0]},
        {"id": "north-wrap", "samples": [359.0, 359.5, 0.0, 0.5, 1.0]},
        {"id": "single-sample", "samples": [123.456]},
        {"id": "antipodal-pair-undefined-mean", "samples": [0.0, 180.0]},
        {"id": "four-quadrants-undefined-mean", "samples": [0.0, 90.0, 180.0, 270.0]},
        {"id": "empty-window", "samples": []},
    ]
    entries = []
    for window in windows:
        mean, resultant = circular_mean_and_resultant(window["samples"])
        entry = {
            "id": window["id"],
            "samples": window["samples"],
            "expectedMeanDeg": mean,
            "expectedResultantLength": resultant,
            "meanIsDefined": mean is not None,
            # §15 decision 3. For an antipodal pair the sines cancel to ~6e-17 rather than
            # to zero, so the mean is numerically defined and arbitrary; only the configured
            # resultant gate rejects it.
            "expectedCircularMeanUndefinedUnderGate": (
                mean is None or resultant < minimum_resultant
            ),
        }
        if mean is not None:
            residuals = [
                abs(shortest_signed_difference_deg(sample, mean)) for sample in window["samples"]
            ]
            entry["expectedResidualsDeg"] = residuals
            entry["expectedResidualP95Deg"] = quantile(residuals, 0.95)
        entries.append(entry)
    return {
        "fixtureVersion": FIXTURE_VERSION,
        "specSections": ["§15", "§19"],
        "minCircularResultantLength": minimum_resultant,
        "weights": "UNIFORM",
        "trimming": "NONE",
        "windows": entries,
    }


def _quaternion_from_rotation_matrix(m: list[list[float]]) -> list[float]:
    """Shepperd's method, written inline so the fixture does not inherit an implementation."""
    trace = m[0][0] + m[1][1] + m[2][2]
    if trace > 0.0:
        s = math.sqrt(trace + 1.0) * 2.0
        q = [(m[2][1] - m[1][2]) / s, (m[0][2] - m[2][0]) / s, (m[1][0] - m[0][1]) / s, 0.25 * s]
    elif m[0][0] > m[1][1] and m[0][0] > m[2][2]:
        s = math.sqrt(1.0 + m[0][0] - m[1][1] - m[2][2]) * 2.0
        q = [0.25 * s, (m[0][1] + m[1][0]) / s, (m[0][2] + m[2][0]) / s, (m[2][1] - m[1][2]) / s]
    elif m[1][1] > m[2][2]:
        s = math.sqrt(1.0 + m[1][1] - m[0][0] - m[2][2]) * 2.0
        q = [(m[0][1] + m[1][0]) / s, 0.25 * s, (m[1][2] + m[2][1]) / s, (m[0][2] - m[2][0]) / s]
    else:
        s = math.sqrt(1.0 + m[2][2] - m[0][0] - m[1][1]) * 2.0
        q = [(m[0][2] + m[2][0]) / s, (m[1][2] + m[2][1]) / s, 0.25 * s, (m[1][0] - m[0][1]) / s]
    norm = math.sqrt(sum(component * component for component in q))
    return [component / norm for component in q]


def _matrix_from_columns(c1, c2, c3) -> list[list[float]]:
    """Columns are the ENU images of device +x, +y, +z respectively."""
    return [[c1[row], c2[row], c3[row]] for row in range(3)]


