# SPEC.md §9 / §9.1 formulas, written out rather than imported.
# --------------------------------------------------------------------------------------
def normalize360(deg: float) -> float:
    wrapped = ((deg % 360.0) + 360.0) % 360.0
    return 0.0 if wrapped == 360.0 else wrapped + 0.0


def shortest_signed_difference_deg(a: float, b: float) -> float:
    radians = math.radians(a - b)
    delta = math.degrees(math.atan2(math.sin(radians), math.cos(radians)))
    return 180.0 if delta == -180.0 else delta


def quantile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    n = len(ordered)
    return ordered[min(n - 1, max(0, math.ceil(q * n) - 1))]


def median(values: list[float]) -> float:
    ordered = sorted(values)
    n = len(ordered)
    if n % 2 == 1:
        return ordered[(n - 1) // 2]
    return (ordered[n // 2 - 1] + ordered[n // 2]) / 2.0


def circular_mean_and_resultant(samples: list[float]) -> tuple[float | None, float]:
    n = len(samples)
    if n == 0:
        return None, 0.0
    cosine = sum(math.cos(math.radians(value)) for value in samples) / n
    sine = sum(math.sin(math.radians(value)) for value in samples) / n
    resultant = min(1.0, max(0.0, math.hypot(cosine, sine)))
    if cosine == 0.0 and sine == 0.0:
        return None, resultant
    return normalize360(math.degrees(math.atan2(sine, cosine))), resultant


def sector_index(heading: float, first_center: float, width: float, count: int) -> int:
    return int(math.floor(normalize360(heading - first_center + width / 2.0) / width)) % count


def _offset_within_sector(heading: float, first_center: float, width: float) -> float:
    """How far past its own start boundary ``heading`` sits, in ``[0, width)``.

    Derived from the *same* wrapped quantity ``sector_index`` uses, so the index and the
    offset cannot disagree by a rounding bit at a boundary.
    """
    wrapped = normalize360(heading - first_center + width / 2.0)
    return wrapped - math.floor(wrapped / width) * width


def straddle_indices(
    heading: float, bound: float, first_center: float, width: float, count: int
) -> list[int]:
    """Every sector intersecting the closed circular interval ``[h - bound, h + bound]``.

    Counted from the arc length rather than by walking until the end index is met: at a bound
    approaching 180 deg the interval wraps almost the whole circle and its two endpoints land
    in the *same* sector, which a walk-until-equal would report as one sector instead of 24.
    """
    if 2.0 * bound >= 360.0:
        return []
    low = heading - bound
    start = sector_index(low, first_center, width, count)
    offset = _offset_within_sector(low, first_center, width)
    spanned = min(count, 1 + int(math.floor((offset + 2.0 * bound) / width)))
    return [(start + step) % count for step in range(spanned)]


