def build_fengshui_classification(rule_set: dict) -> dict:
    count = int(rule_set["sectorCount"])
    width = float(rule_set["sectorWidthDeg"])
    first_center = float(rule_set["firstSectorCenterDeg"])
    names = {int(sector["index"]): sector["name"] for sector in rule_set["sectors"]}
    epsilon = 1e-9

    cases = []
    for index in range(count):
        center = normalize360(first_center + index * width)
        start = normalize360(center - width / 2.0)
        end = normalize360(center + width / 2.0)
        probes = [
            ("center", center),
            ("start-boundary", start),
            ("end-boundary", end),
            ("start-minus-epsilon", start - epsilon),
            ("start-plus-epsilon", start + epsilon),
            ("start-minus-0.1", start - 0.1),
            ("start-plus-0.1", start + 0.1),
            ("start-minus-1.0", start - 1.0),
            ("start-plus-1.0", start + 1.0),
        ]
        for label, raw in probes:
            heading = normalize360(raw)
            expected = sector_index(heading, first_center, width, count)
            cases.append(
                {
                    "id": f"sector-{index:02d}-{label}",
                    "declaredSectorIndex": index,
                    "headingDeg": heading,
                    "expectedSectorIndex": expected,
                    "expectedSectorName": names[expected],
                }
            )

    straddle_cases = []
    for heading, bound, note in [
        (189.0, 7.0, "the §22.1 example: 7.0 deg straddles the 187.5 boundary"),
        (0.0, 0.0, "a zero bound is one sector"),
        (0.0, 1.0, "north wrap, symmetric across 0/360"),
        (352.5, 0.0, "exactly on the boundary separating ren and zi"),
        (352.5, 0.5, "straddling that boundary"),
        (7.5, 0.0, "exactly on a boundary belongs to the sector it starts"),
        (100.0, 7.5, "a bound above 7.5 guarantees at least two sectors"),
        (100.0, 20.0, "above 15 deg guarantees at least three"),
        (
            10.0,
            179.0,
            "nearly the whole circle: both endpoints land in the same sector, which a "
            "walk-until-equal implementation would report as one sector instead of 24",
        ),
        (10.0, 180.0, "2*bound == 360: no classification is possible"),
        (10.0, 200.0, "2*bound > 360: no classification is possible"),
    ]:
        indices = straddle_indices(heading, bound, first_center, width, count)
        straddle_cases.append(
            {
                "headingDeg": heading,
                "reportedBound95Deg": bound,
                "note": note,
                "expectedSectorIndices": indices,
                "expectedSectorNames": [names[index] for index in indices],
                "expectedBoundaryStraddled": len(indices) != 1,
                "classificationPossible": len(indices) > 0,
            }
        )

    return {
        "fixtureVersion": FIXTURE_VERSION,
        "specSections": ["§21.1", "§21.3", "§21.4"],
        "ruleSetVersion": rule_set["ruleSetVersion"],
        "sectorIndexFormula": (
            "floor(normalize360(h - firstSectorCenterDeg + sectorWidthDeg/2) / sectorWidthDeg) "
            "mod sectorCount"
        ),
        "boundaryEpsilonDeg": epsilon,
        "sectorCases": cases,
        "straddleCases": straddle_cases,
    }


def build_fengshui_reference_transform() -> dict:
    """§21.2 under **both** hidden Google hypotheses and both ruleset references.

    Let ``g`` be the Google output and ``d`` the declination. If Google secretly emitted true
    north, TRUE uses ``g`` exactly and MAGNETIC uses ``g-d`` exactly. If Google secretly
    emitted magnetic north, the TRUE point ``g`` is wrong by ``|d|`` and the derived MAGNETIC
    point ``g-d`` is *also* wrong by ``|d|``; ``referenceAmbiguityBound95Deg = |d|`` covers
    either hypothesis. Subtracting ``d`` for a magnetic ruleset MUST NOT zero the term.
    """
    cases = []
    for declination in (1.5, -1.5):
        for google_output in (0.0, 7.4, 352.6, 189.0):
            for hidden in ("GOOGLE_EMITTED_TRUE", "GOOGLE_EMITTED_MAGNETIC"):
                actual_true = (
                    google_output
                    if hidden == "GOOGLE_EMITTED_TRUE"
                    else normalize360(google_output + declination)
                )
                for reference_selection in ("TRUE", "MAGNETIC"):
                    point_estimate = (
                        google_output
                        if reference_selection == "TRUE"
                        else normalize360(google_output - declination)
                    )
                    truth = (
                        actual_true
                        if reference_selection == "TRUE"
                        else normalize360(actual_true - declination)
                    )
                    cases.append(
                        {
                            "id": (
                                f"d{declination:+}-g{google_output}-{hidden}-{reference_selection}"
                            ),
                            "caseKind": "HIDDEN_HYPOTHESIS",
                            "googleOutputDeg": google_output,
                            "declinationDeg": declination,
                            "hiddenHypothesis": hidden,
                            "referenceSelection": reference_selection,
                            "needleOffsetDeg": 0.0,
                            "expectedClassificationHeadingDeg": point_estimate,
                            "truthUnderHypothesisDeg": truth,
                            "referenceAmbiguityBound95Deg": abs(declination),
                            "expectedErrorDeg": abs(
                                shortest_signed_difference_deg(point_estimate, truth)
                            ),
                        }
                    )
    # A ruleset needle offset is a declared doctrinal plate convention, never an instrument
    # correction: it shifts the classification heading and nothing else. Its "error" against
    # an un-offset truth is the doctrine, not measurement uncertainty, so these cases are
    # tagged NEEDLE_OFFSET and are deliberately outside the ambiguity-coverage check.
    for offset in (7.5, -7.5):
        cases.append(
            {
                "id": f"needle-offset{offset:+}",
                "caseKind": "NEEDLE_OFFSET",
                "googleOutputDeg": 100.0,
                "declinationDeg": 0.0,
                "hiddenHypothesis": "GOOGLE_EMITTED_TRUE",
                "referenceSelection": "TRUE",
                "needleOffsetDeg": offset,
                "expectedClassificationHeadingDeg": normalize360(100.0 + offset),
                "truthUnderHypothesisDeg": 100.0,
                "referenceAmbiguityBound95Deg": 0.0,
                "expectedErrorDeg": abs(offset),
            }
        )
    return {
        "fixtureVersion": FIXTURE_VERSION,
        "specSections": ["§11", "§21.2"],
        "cases": cases,
    }


